<?php
/**
 * 博客点赞系统 — 配置文件
 *
 * 【部署前必须改三处】
 *   1. $DB_NAME / $DB_USER / $DB_PASS —— 虚拟主机面板里创建的数据库信息
 *   2. $SALT —— 换成一段随机字符串（越乱越好，32 位以上）
 *   3. $ALLOWED_ORIGINS —— 换成你博客的真实域名
 *
 * 【不要做的事】
 *   - 不要把填好真实密码的这份文件传到公开仓库
 *   - 不要把 $DEBUG 在生产环境打开
 *
 * @package BlogLikes
 * @version 1.0.0
 */

// 非入口文件守卫：直接访问本文件会得到 403，而不是把配置内容暴露出去
if (!defined('LIKES_APP')) {
    http_response_code(403);
    exit('Forbidden');
}

/* ============================================================
 * 一、数据库连接
 * 优先读环境变量，读不到才用下面的默认值。
 * 这样同一份代码可以本地、测试机、生产机通吃，改环境变量即可。
 * ============================================================ */

$DB_HOST   = getenv('LIKES_DB_HOST')   ?: 'localhost';      // 多数虚拟主机就是 localhost
$DB_PORT   = getenv('LIKES_DB_PORT')   ?: '3306';

// 库名与用户名。在虚拟主机面板建库时会给，库名通常带主机商前缀（如 abc123_likes）。
$DB_NAME   = getenv('LIKES_DB_NAME')   ?: 'your_database_name';
$DB_USER   = getenv('LIKES_DB_USER')   ?: 'your_database_user';

// 三项都留成一眼看得出「还没填」的占位符，而不是看起来像真值的默认值：
// 万一忘了改，MySQL 会明确报「密码错」，而不是留下一个让人摸不着头脑的连接超时。
$DB_PASS   = getenv('LIKES_DB_PASS')   ?: 'your_database_password';

$DB_CHARSET = 'utf8mb4';

// 少数虚拟主机不用 TCP 而走 socket（面板里会写「socket: /tmp/mysql.sock」）。
// 留空表示不用 socket；填了就只走 socket，忽略 host/port。
$DB_SOCKET = getenv('LIKES_DB_SOCKET') ?: '';

/* ============================================================
 * 二、加盐（salt）
 * 前端传来的 visitor_id 会先和这个 salt 拼起来再哈希，才落到数据库。
 * 所以数据库里存的是不可逆的哈希值，不存访客原始标识，保护隐私。
 *
 * 换成你自己的随机串，例如：
 *   $SALT = 'k9F2mQ7x R4pL1zT8vN3bY6wH0sJ5dG2a';
 *
 * 注意：改了 salt 之后，老访客算出的哈希会变，会被当成新访客，
 *       也就是他们可以对自己以前赞过的文章再赞一次。上线后再别改。
 * ============================================================ */
$SALT = 'CHANGE_ME_PLEASE_REPLACE_WITH_A_LONG_RANDOM_STRING';

/* ============================================================
 * 三、CORS 白名单
 * 只有列表里的域名，浏览器才允许跨域调用这个 API。
 * 生产环境绝对不要写 '*'，否则任何网站都能替你刷赞。
 *
 * 如果前端和 API 同域（比如都在 blog.example.com 下），
 * 这里其实用不上，但建议照样填上，方便以后把 API 挪到子域。
 *
 * ⚠️ 最容易踩的坑：你「用来访问的域名」必须在这个列表里。
 *    浏览器在跨域时会发 Origin 头，但——同源的 POST 请求也会发 Origin，
 *    而同源的 GET 请求不发。
 *    后果是：GET 查询一切正常，一点赞就返回 400 origin not allowed。
 *    看到这个症状，九成是这里少写了你正在用的域名。
 *    所以：博客域名、测试域名、虚拟主机自带域名，全都列上。
 *
 * 两种写法：
 *   'https://blog.example.com'    精确匹配这一个来源
 *   'https://*.example.com'       放行 example.com 的所有子域（不含裸域名本身）
 * ============================================================ */
$ALLOWED_ORIGINS = array(
    'https://blog.example.com',
    'https://www.example.com',
    'https://blog.example.com',
    'https://staging.example.com',              // 虚拟主机自带域名，直接访问/测试时会用到

    // 通配写法：放行 example.com 的**所有子域**（blog. / www. / 以后再加的都不用改这里）。
    // 注意：只匹配子域，不含 example.com 本身；要放行裸域名就再单独写一行。
    'https://*.example.com',
);

/* ============================================================
 * 四、防刷限流
 * 统计同一 IP 在时间窗内的点赞次数，超了就返回 429。
 * 注意：这里的"次数"指成功写入的点赞，重复点同一篇不会计入，
 *       所以正常用户几乎不可能触发，主要拦脚本批量刷不同文章。
 * ============================================================ */
$RATE_LIMIT_ENABLED = true;
$RATE_LIMIT_MAX     = 30;    // 窗口内最多点赞次数
$RATE_LIMIT_WINDOW  = 60;    // 窗口长度（秒）

// 套了 Cloudflare / 宝塔反代 / Nginx 反代时才设 true，
// 否则客户端可以伪造 X-Forwarded-For 来绕过限流。
$TRUST_PROXY = false;

/* ============================================================
 * 五、其它
 * ============================================================ */

// 批量查询接口一次最多查询多少篇文章
$MAX_BATCH_IDS = 100;

// 是否记录错误日志。留空 $LOG_FILE 则写进 PHP 的错误日志（虚拟主机面板可查）
$LOG_ERRORS = true;
$LOG_FILE   = '';

// 生产环境必须 false。true 时接口会在报错响应里附带 data.debug，
// 里面可能含有数据库信息，只在你排查问题时临时打开。
$DEBUG = false;

/* ============================================================
 * 六、本地配置覆盖（强烈建议用）
 * ============================================================
 *
 * 上面是模板默认值。如果你在同目录放一个 config.local.php，
 * 它会在最后执行，**覆盖上面任何一项**。
 *
 * 为什么建议用：
 *   升级时通常是把整个压缩包重新上传解压，这会把本文件覆盖回模板状态 ——
 *   你的数据库密码就丢了，每次都得重填一遍，而每次重填都是一次填错的机会。
 *
 *   把真正要改的东西（数据库密码、salt、白名单）放进 config.local.php，
 *   它就永远不会被解压覆盖，一次配好、长期有效。
 *
 * 怎么用：
 *   1) 把同目录的 config.local.example.php 复制成 config.local.php
 *   2) 照里面的注释填你自己的值
 *   3) 之后升级只覆盖其他文件，这个文件不用动
 *
 * 没有这个文件也完全正常，上面的默认值照常生效。
 * ============================================================ */

$localConfig = __DIR__ . '/config.local.php';
if (is_file($localConfig)) {
    require $localConfig;
}
